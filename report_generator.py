# Main entry point
# ---------------------------------------------------------------------------
def generate_report(
    score,
    category,
    skill_score,
    text_similarity,
    experience_score,
    matched,
    missing,
    suggestions,
    recommended_jobs,
    gap_analysis=None,
):
    """
    Generate the ATS analysis PDF and return its file path.

    gap_analysis: optional dict from analyze_resume_job_gap() containing
      partial_matches, prioritized_gaps, roadmap, and recommendations.
    """
    os.makedirs("reports", exist_ok=True)

    styles = _build_styles()

    # Build document with header/footer canvas callbacks
    pdf = SimpleDocTemplate(
        REPORT_FILE_PATH,
        pagesize=letter,
        rightMargin=RIGHT_MARGIN,
        leftMargin=LEFT_MARGIN,
        topMargin=TOP_MARGIN + 36,   # extra clearance for header bar
        bottomMargin=BOTTOM_MARGIN + 28,  # extra clearance for footer
        title=f"{BRAND_NAME} — ATS Analysis Report",
        author=BRAND_NAME,
        subject="ATS Resume Evaluation Report",
    )

    story = []

    # -----------------------------------------------------------------------
    # Cover block
    # -----------------------------------------------------------------------
    story.append(Paragraph(BRAND_NAME, styles["report_title"]))
    story.append(Paragraph(REPORT_SUBTITLE, styles["report_subtitle"]))
    story.append(Spacer(1, 10))

    # -----------------------------------------------------------------------
    # Score Summary
    # -----------------------------------------------------------------------
    _section(story, "ATS Score Summary", styles, [
        _score_table(score, category, skill_score, text_similarity, experience_score),
    ])

    # -----------------------------------------------------------------------
    # Matched Skills
    # -----------------------------------------------------------------------
    _skill_list_section(
        story,
        "Matched Skills",
        [format_skill(s) for s in (matched or [])],
        "No matched skills found.",
        styles,
    )

    # -----------------------------------------------------------------------
    # Missing Skills
    # -----------------------------------------------------------------------
    _skill_list_section(
        story,
        "Missing Skills",
        [format_skill(s) for s in (missing or [])],
        "No missing skills identified.",
        styles,
    )

    # -----------------------------------------------------------------------
    # Partial / Related Skills (from gap_analysis)
    # -----------------------------------------------------------------------
    partial_matches = (gap_analysis or {}).get("partial_matches", [])
    if partial_matches:
        tbl = _partial_skills_table(partial_matches)
        _section(story, "Partial / Related Skills", styles, [
            Paragraph(
                "These skills partially satisfy a requirement (50% credit applied).",
                styles["muted"],
            ),
            Spacer(1, 4),
            tbl,
        ])

    # -----------------------------------------------------------------------
    # Suggestions
    # -----------------------------------------------------------------------
    if suggestions:
        elements = []
        for sug in suggestions:
            elements.append(Paragraph(f"\u2022  {sug}", styles["bullet"]))
        _section(story, "Improvement Suggestions", styles, elements)

    # -----------------------------------------------------------------------
    # Gap Analysis Coverage
    # -----------------------------------------------------------------------
    coverage = (gap_analysis or {}).get("skill_coverage")
    if coverage and coverage.get("total_requirements", 0) > 0:
        cov_data = [
            ["Coverage Metric", "Value"],
            ["Total Requirements", str(coverage["total_requirements"])],
            ["Exact Matches", str(coverage["exact_matches"])],
            ["Partial Matches", str(coverage["partial_matches"])],
            ["Missing", str(coverage["missing"])],
            ["Effective Coverage", f'{coverage["coverage_percentage"]}%'],
        ]
        col_w = [2.4 * inch, 1.8 * inch]
        t = Table(cov_data, colWidths=col_w, hAlign="LEFT")
        t.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
            ("BACKGROUND", (0, 0), (-1, 0), PRIMARY_COLOR),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
            ("FONTSIZE", (0, 0), (-1, -1), 10),
            ("TEXTCOLOR", (0, 1), (-1, -1), TEXT_COLOR),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, SURFACE_COLOR]),
        ]))
        _section(story, "Gap Analysis Coverage", styles, [t])

    # -----------------------------------------------------------------------
    # Prioritized Improvement Roadmap
    # -----------------------------------------------------------------------
    roadmap = (gap_analysis or {}).get("roadmap", {})
    immediate = roadmap.get("immediate", [])
    next_gaps = roadmap.get("next", [])
    optional_gaps = roadmap.get("optional", [])

    if immediate or next_gaps or optional_gaps:
        story.append(HRFlowable(width=CONTENT_WIDTH, thickness=0.5, color=BORDER_COLOR, spaceAfter=4))
        story.append(Paragraph("Resume Improvement Roadmap", styles["section_heading"]))

        if immediate:
            story.append(Paragraph(
                "<b>Immediate Priorities</b> — High impact gaps to address first",
                styles["muted"],
            ))
            story.append(Spacer(1, 3))
            tbl = _roadmap_table(immediate, "HIGH", ACCENT_DANGER, colors.white)
            if tbl:
                story.append(tbl)
            story.append(Spacer(1, 8))

        if next_gaps:
            story.append(Paragraph(
                "<b>Next Priorities</b> — Medium impact gaps",
                styles["muted"],
            ))
            story.append(Spacer(1, 3))
            tbl = _roadmap_table(next_gaps, "MEDIUM", ACCENT_WARNING, colors.white)
            if tbl:
                story.append(tbl)
            story.append(Spacer(1, 8))

        if optional_gaps:
            story.append(Paragraph(
                "<b>Optional Enhancements</b> — Nice-to-have improvements",
                styles["muted"],
            ))
            story.append(Spacer(1, 3))
            tbl = _roadmap_table(optional_gaps, "LOW", SURFACE_ALT, TEXT_COLOR)
            if tbl:
                story.append(tbl)
            story.append(Spacer(1, 8))

    # -----------------------------------------------------------------------
    # AI Roadmap (optional)
    # -----------------------------------------------------------------------
    ai_roadmap = (gap_analysis or {}).get("ai_roadmap")
    if ai_roadmap and isinstance(ai_roadmap, str) and ai_roadmap.strip():
        ai_lines = [line.strip() for line in ai_roadmap.strip().splitlines() if line.strip()]
        ai_elements = [
            Paragraph(
                "AI-generated improvement guidance (supplementary only — does not affect ATS score):",
                styles["muted"],
            ),
            Spacer(1, 4),
            *[Paragraph(line, styles["ai_body"]) for line in ai_lines],
        ]
        _section(story, "AI Improvement Guidance", styles, ai_elements)

    # -----------------------------------------------------------------------
    # Recommended Jobs
    # -----------------------------------------------------------------------
    tbl = _jobs_table(recommended_jobs)
    if tbl:
        _section(story, "Recommended Job Roles", styles, [tbl])
    else:
        _section(story, "Recommended Job Roles", styles, [
            Paragraph("No job role recommendations available.", styles["muted"]),
        ])

    # -----------------------------------------------------------------------
    # Footer note
    # -----------------------------------------------------------------------
    story.append(Spacer(1, 24))
    story.append(HRFlowable(width=CONTENT_WIDTH, thickness=0.5, color=BORDER_COLOR))
    story.append(Spacer(1, 6))
    story.append(Paragraph(
        f"<i>This report was generated by <b>{BRAND_NAME}</b>. "
        "ATS scores are deterministic and are not modified by AI features. "
        "Score formula: 50% Skill Match + 30% Text Similarity + 20% Experience Match.</i>",
        styles["muted"],
    ))

    # -----------------------------------------------------------------------
    # Build PDF
    # -----------------------------------------------------------------------
    pdf.build(story, onFirstPage=_draw_header_footer, onLaterPages=_draw_header_footer)

    return REPORT_FILE_PATH