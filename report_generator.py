def format_skill(skill):
    """Return a display-formatted version of a canonical skill name."""
    if not skill:
        return ""
    if " or " in skill:
        return " or ".join(format_skill(part) for part in skill.split(" or "))
    return SKILL_MAP.get(skill.strip().lower(), skill.strip().title())


# ---------------------------------------------------------------------------
# Page canvas callbacks (header / footer)
# ---------------------------------------------------------------------------
def _draw_header_footer(canvas, doc):
    """Draw branding header and page-number footer on every page."""
    canvas.saveState()
    page_num = doc.page

    # --- Header bar ---
    canvas.setFillColor(HEADER_BG)
    canvas.rect(0, PAGE_H - 36, PAGE_W, 36, fill=1, stroke=0)
    canvas.setFont("Helvetica-Bold", 13)
    canvas.setFillColor(colors.white)
    canvas.drawString(LEFT_MARGIN, PAGE_H - 24, BRAND_NAME)
    canvas.setFont("Helvetica", 9)
    canvas.setFillColor(colors.HexColor("#93c5fd"))
    canvas.drawRightString(PAGE_W - RIGHT_MARGIN, PAGE_H - 24, REPORT_SUBTITLE)

    # --- Footer divider ---
    canvas.setStrokeColor(BORDER_COLOR)
    canvas.setLineWidth(0.5)
    canvas.line(LEFT_MARGIN, 40, PAGE_W - RIGHT_MARGIN, 40)

    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED_COLOR)
    canvas.drawString(LEFT_MARGIN, 26,
                      f"Generated by {BRAND_NAME} | {datetime.now().strftime('%d %b %Y')}")
    canvas.drawRightString(PAGE_W - RIGHT_MARGIN, 26, f"Page {page_num}")

    canvas.restoreState()


