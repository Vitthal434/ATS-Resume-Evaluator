# ---------------------------------------------------------------------------
# Section builder helpers
# ---------------------------------------------------------------------------
def _section(story, title, styles, elements):
    """Wrap a section heading + content in KeepTogether to avoid orphan headers."""
    block = [
        HRFlowable(width=CONTENT_WIDTH, thickness=0.5, color=BORDER_COLOR, spaceAfter=4),
        Paragraph(title, styles["section_heading"]),
        Spacer(1, 4),
        *elements,
    ]
    story.append(KeepTogether(block[:3]))   # Keep heading glued to first element
    for el in block[3:]:
        story.append(el)


def _skill_list_section(story, title, skills, empty_text, styles):
    """Render a labelled skill list section."""
    elements = []
    tbl = _skills_table(skills, empty_text)
    if tbl:
        elements.append(tbl)
    else:
        elements.append(Paragraph(empty_text, styles["muted"]))
    _section(story, title, styles, elements)


